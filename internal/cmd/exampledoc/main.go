// Command exampledoc writes the testable examples of the module to a Markdown
// file.
//
// Usage:
//
//	exampledoc [-check] [-o file]
//
// Run the command in the directory of the go.mod file.  The command finds
// each package of the module that has example functions in its _test.go
// files.  The command does not look in the internal packages, in testdata
// directories, in vendor, in a nested module, or in a directory with a name
// that starts with "." or "_".  The sections of the file are in order of
// import path, so the root package is first.
//
// For each example, the Markdown file shows the doc comment, the complete
// program, and the output.  Each example must be in an external test package,
// such as stdout_test.  An example must use only the declarations in its own
// file.
//
// The -o flag names the Markdown file.  The default is docs/examples.md.
//
// With -check, the command does not write the Markdown file.  The command
// exits with status 1 if the Markdown file is different from the generated
// text.
package main

import (
	"bytes"
	"cmp"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/build"
	"go/doc"
	"go/doc/comment"
	"go/format"
	"go/parser"
	"go/token"
	"io/fs"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"unicode"
	"unicode/utf8"
)

// filePerm is the permission of the Markdown file if the command creates it.
const filePerm = 0o600

const header = `<!-- Code generated by exampledoc. DO NOT EDIT. -->

# gslog Examples

This file shows each testable example of the gslog packages as a complete
program. ` + "`go test`" + ` runs each example that shows an output. Then it
compares the output of the example with the output below the program. Run
` + "`make docs`" + ` to update this file.
`

func main() {
	log.SetFlags(0)
	log.SetPrefix("exampledoc: ")

	err := run()
	if err != nil {
		log.Fatal(err)
	}
}

// run parses the command line, and then writes or compares the Markdown
// file.
func run() error {
	out := flag.String("o", "docs/examples.md", "the Markdown file")
	check := flag.Bool("check", false, "compare the file with the generated text, and do not write it")

	flag.Parse()

	if flag.NArg() > 0 {
		return errors.New("the command takes no arguments")
	}

	text, err := render(".")
	if err != nil {
		return err
	}

	if *check {
		return compare(*out, text)
	}

	return os.WriteFile(*out, text, filePerm)
}

// render returns the Markdown text for the packages of the module in root
// that have examples.
func render(root string) ([]byte, error) {
	goMod := filepath.Join(root, "go.mod")

	module, err := modulePath(goMod)
	if err != nil {
		return nil, err
	}

	pkgs, err := loadPackages(root, module)
	if err != nil {
		return nil, err
	}

	var buf bytes.Buffer

	buf.WriteString(header)

	for _, p := range pkgs {
		err = renderPackage(&buf, p)
		if err != nil {
			return nil, err
		}
	}

	return buf.Bytes(), nil
}

// pkg is a package of the module that has examples.
type pkg struct {
	importPath string
	name       string
	doc        string
	fset       *token.FileSet
	examples   []*doc.Example
}

// loadPackages returns the packages of the module in root that have
// examples, in order of import path.  The root package is first.  The walk
// does not enter a nested module.
func loadPackages(root, module string) ([]*pkg, error) {
	var pkgs []*pkg

	err := filepath.WalkDir(root, func(dir string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}

		if !d.IsDir() {
			return nil
		}

		if dir != root && (skipDir(d.Name()) || isModuleRoot(dir)) {
			return filepath.SkipDir
		}

		rel, err := filepath.Rel(root, dir)
		if err != nil {
			return err
		}

		pkgPath := importPath(module, rel)

		p, err := loadPackage(dir, pkgPath)
		if err != nil {
			return err
		}

		if p != nil {
			pkgs = append(pkgs, p)
		}

		return nil
	})
	if err != nil {
		return nil, err
	}

	slices.SortFunc(pkgs, func(a, b *pkg) int {
		return strings.Compare(a.importPath, b.importPath)
	})

	return pkgs, nil
}

// skipDir reports whether the walk does not enter the directory with the
// name.  The walk does not enter internal, testdata, vendor, and a directory
// with a name that starts with "." or "_".
func skipDir(name string) bool {
	switch name {
	case "internal", "testdata", "vendor":
		return true
	}

	return strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_")
}

// isModuleRoot reports whether dir has a go.mod file.
func isModuleRoot(dir string) bool {
	goMod := filepath.Join(dir, "go.mod")

	_, err := os.Stat(goMod)

	return err == nil
}

// loadPackage returns the package in dir with its examples.  loadPackage
// returns nil when dir has no Go files, or when the package has no examples.
func loadPackage(dir, importPath string) (*pkg, error) {
	bp, err := build.ImportDir(dir, 0)

	var noGo *build.NoGoError
	if errors.As(err, &noGo) {
		return nil, nil
	}

	if err != nil {
		return nil, err
	}

	fset := token.NewFileSet()

	pkgDoc, err := packageDoc(fset, dir, bp.GoFiles)
	if err != nil {
		return nil, err
	}

	testFiles := slices.Concat(bp.TestGoFiles, bp.XTestGoFiles)

	tests, err := parseFiles(fset, dir, testFiles)
	if err != nil {
		return nil, err
	}

	examples := doc.Examples(tests...)
	if len(examples) == 0 {
		return nil, nil
	}

	slices.SortFunc(examples, func(a, b *doc.Example) int {
		return cmp.Compare(a.Code.Pos(), b.Code.Pos())
	})

	return &pkg{
		importPath: importPath,
		name:       bp.Name,
		doc:        pkgDoc,
		fset:       fset,
		examples:   examples,
	}, nil
}

// packageDoc returns the package doc comment from the non-test files in dir.
func packageDoc(fset *token.FileSet, dir string, files []string) (string, error) {
	pkgDoc := ""

	for _, file := range files {
		name := filepath.Join(dir, file)

		f, err := parser.ParseFile(fset, name, nil, parser.PackageClauseOnly|parser.ParseComments)
		if err != nil {
			return "", err
		}

		if f.Doc != nil {
			pkgDoc = f.Doc.Text()
		}
	}

	return pkgDoc, nil
}

// parseFiles parses the test files in dir.
func parseFiles(fset *token.FileSet, dir string, files []string) ([]*ast.File, error) {
	parsed := make([]*ast.File, 0, len(files))

	for _, file := range files {
		name := filepath.Join(dir, file)

		f, err := parser.ParseFile(fset, name, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}

		parsed = append(parsed, f)
	}

	return parsed, nil
}

// renderPackage writes the package doc comment and the examples of p to buf.
// The examples are in order of file name, and then in source order.
func renderPackage(buf *bytes.Buffer, p *pkg) error {
	synopsis := markdown(p.doc)

	fmt.Fprintf(buf, "\n## %s\n\n%s", p.importPath, synopsis)

	for _, ex := range p.examples {
		err := renderExample(buf, p.fset, p.name, ex)
		if err != nil {
			return fmt.Errorf("%s: %w", p.importPath, err)
		}
	}

	return nil
}

// renderExample writes the title, the doc comment, the complete program, and
// the output of ex to buf.
func renderExample(buf *bytes.Buffer, fset *token.FileSet, pkg string, ex *doc.Example) error {
	if ex.Play == nil {
		return fmt.Errorf("example %s is not a complete program: "+
			"it must be in an external test package and use only the declarations in its own file", ex.Name)
	}

	var program bytes.Buffer

	err := format.Node(&program, fset, ex.Play)
	if err != nil {
		return fmt.Errorf("example %s: %w", ex.Name, err)
	}

	heading := title(pkg, ex)

	fmt.Fprintf(buf, "\n### %s\n\n", heading)

	if ex.Doc != "" {
		description := markdown(ex.Doc)

		fmt.Fprintf(buf, "%s\n", description)
	}

	fmt.Fprintf(buf, "```go\n%s```\n", program.Bytes())

	if ex.Output != "" {
		label := "Output"
		if ex.Unordered {
			label = "Output, in any order"
		}

		fmt.Fprintf(buf, "\n%s:\n\n```text\n%s```\n", label, ex.Output)
	}

	return nil
}

// importPath returns the import path of the package in dir.  dir is relative
// to the directory of the module.  The import path of "." is the module path.
func importPath(module, dir string) string {
	dir = filepath.ToSlash(filepath.Clean(dir))
	if dir == "." {
		return module
	}

	return module + "/" + dir
}

// title returns the heading of ex, such as "stdout.NewHandler
// (withSourceAdded)".  A suffix is the part of the example name after the
// last underscore, if that part starts with a lowercase letter.
func title(pkg string, ex *doc.Example) string {
	symbol, suffix := ex.Name, ""

	i := strings.LastIndex(symbol, "_")
	if i >= 0 {
		first, _ := utf8.DecodeRuneInString(symbol[i+1:])
		if unicode.IsLower(first) {
			symbol, suffix = symbol[:i], symbol[i+1:]
		}
	}

	t := pkg
	if symbol != "" {
		t += "." + strings.ReplaceAll(symbol, "_", ".")
	}

	if suffix != "" {
		t += " (" + suffix + ")"
	}

	return t
}

// markdown returns the doc comment text as Markdown.
func markdown(text string) string {
	var p comment.Parser

	d := p.Parse(text)

	pr := comment.Printer{HeadingLevel: 4}

	return string(pr.Markdown(d))
}

// modulePath returns the module path in the go.mod file at path.
func modulePath(path string) (string, error) {
	b, err := os.ReadFile(filepath.Clean(path))
	if err != nil {
		return "", err
	}

	for line := range strings.Lines(string(b)) {
		module, ok := strings.CutPrefix(line, "module ")
		if ok {
			return strings.TrimSpace(module), nil
		}
	}

	return "", fmt.Errorf("%s: no module directive", path)
}

// compare returns an error if the file at path is different from text.
func compare(path string, text []byte) error {
	current, err := os.ReadFile(filepath.Clean(path))
	if err != nil {
		return err
	}

	if !bytes.Equal(current, text) {
		return fmt.Errorf("%s is out of date; run make docs", path)
	}

	return nil
}
